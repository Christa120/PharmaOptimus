import { Facility, FacilityStockItem } from '../types/pharma';
import { TRACER_MEDICINES } from './medicines';

// Fonction helper pour générer des stocks réalistes calibrés selon le type et la taille d'établissement
function generateRealisticStock(facilityType: string, servedPop: number, hasColdChain: boolean, seedIndex: number): FacilityStockItem[] {
  return TRACER_MEDICINES.map((prod, pIdx) => {
    // Échelle de consommation selon la population et le type
    const popScale = Math.max(0.2, servedPop / 100000);
    const typeFactor = facilityType === 'central_depot' ? 25 : facilityType === 'referral_hospital' ? 3.5 : facilityType === 'health_center' ? 1.0 : 0.8;
    
    // Consommation hebdomadaire moyenne
    const baseWeekly = Math.round((prod.criticality === 'vital' ? 60 : 35) * popScale * typeFactor);
    const weeklyConsumptionAvg = Math.max(5, baseWeekly);
    
    // Simulation contrôlée de variations : certains produits en rupture, d'autres en équilibre ou surstock
    const varFactor = Math.sin(seedIndex * 1.7 + pIdx * 2.3);
    let qtyOnHand = 0;
    let qtyExpiring30d = 0;
    let qtyExpiring90d = 0;
    
    // Cas d'incompatibilité de chaîne du froid
    if (prod.requiresColdChain && !hasColdChain && facilityType !== 'central_depot') {
      qtyOnHand = 0;
      return {
        productId: prod.id,
        qtyOnHand: 0,
        qtyExpiring30d: 0,
        qtyExpiring90d: 0,
        weeklyConsumptionAvg: 0,
        daysOfCover: 0,
        status: 'critical_stockout',
      };
    }
    
    if (varFactor < -0.45) {
      // Rupture imminente ou critique (< 7 jours de couverture)
      qtyOnHand = Math.round(weeklyConsumptionAvg * 0.4);
    } else if (varFactor < 0.05) {
      // Tension / stock bas (7 à 20 jours)
      qtyOnHand = Math.round(weeklyConsumptionAvg * 1.8);
    } else if (varFactor < 0.70) {
      // Stock sain (21 à 60 jours)
      qtyOnHand = Math.round(weeklyConsumptionAvg * 5.2);
    } else {
      // Surstock / risque de péremption (> 65 jours)
      qtyOnHand = Math.round(weeklyConsumptionAvg * 11.5);
      qtyExpiring30d = Math.round(qtyOnHand * 0.12);
      qtyExpiring90d = Math.round(qtyOnHand * 0.35);
    }
    
    const daysOfCover = weeklyConsumptionAvg > 0 ? Math.round((qtyOnHand / (weeklyConsumptionAvg / 7)) * 10) / 10 : 0;
    
    let status: FacilityStockItem['status'] = 'balanced';
    if (daysOfCover < 7) status = 'critical_stockout';
    else if (daysOfCover < 21) status = 'low_stock';
    else if (daysOfCover > 60 && qtyExpiring90d > 0) status = 'overstock_expiry';
    
    return {
      productId: prod.id,
      qtyOnHand,
      qtyExpiring30d,
      qtyExpiring90d,
      weeklyConsumptionAvg,
      daysOfCover,
      status,
    };
  });
}

