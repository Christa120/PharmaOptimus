// Calcul initial des stocks et du score de priorité selon la formule définie dans le cahier des charges
export const INITIAL_FACILITIES: Facility[] = RAW_FACILITIES.map((raw, idx) => {
  const stocks = generateRealisticStock(raw.type, raw.servedPopulation, raw.hasColdChain, idx);
  
  // R : Risque de rupture (max de probabilité ou pourcentage de produits en rupture imminente)
  const stockoutItems = stocks.filter(s => s.daysOfCover < 7);
  const stockoutRisk = Math.min(1.0, stockoutItems.length / 3);
  
  // C : Criticité clinique (part de produits vitaux en tension)
  const vitalItemsInDanger = stocks.filter(s => {
    const p = TRACER_MEDICINES.find(m => m.id === s.productId);
    return p?.criticality === 'vital' && s.daysOfCover < 14;
  });
  const clinicalCriticality = Math.min(1.0, vitalItemsInDanger.length / 2);
  
  // P : Population desservie (logarithme normalisé sur [0, 1])
  const minLog = Math.log(20000);
  const maxLog = Math.log(1000000);
  const popClamped = Math.min(1000000, Math.max(20000, raw.servedPopulation));
  const populationScore = Math.min(1.0, Math.max(0, (Math.log(popClamped) - minLog) / (maxLog - minLog)));
  
  // T : Temps depuis dernière livraison (normalisé sur 35 jours max)
  const timeSinceDelivery = Math.min(1.0, raw.lastDeliveryDaysAgo / 35);
  
  // Formule officielle : 100 * (0.40 * R + 0.25 * C + 0.20 * P + 0.15 * T)
  const totalScore = Math.round(
    100 * (0.40 * stockoutRisk + 0.25 * clinicalCriticality + 0.20 * populationScore + 0.15 * timeSinceDelivery)
  );

  return {
    ...raw,
    stocks,
    priorityScore: raw.type === 'central_depot' ? 0 : totalScore,
    priorityBreakdown: {
      stockoutRisk: Math.round(stockoutRisk * 100) / 100,
      clinicalCriticality: Math.round(clinicalCriticality * 100) / 100,
      populationScore: Math.round(populationScore * 100) / 100,
      timeSinceDelivery: Math.round(timeSinceDelivery * 100) / 100,
    },
  };
});
